"""Make named game functions hookable in the port's generated code.

Mercenaries Recompiled's generated C calls game functions directly by name
(sub_XXXXXXXX). To let plugins hook one, this renames its generated
definition to sub_XXXXXXXX_body and writes recomp/gen/foundry_hooks.c with a
wrapper under the original name. Every caller (direct calls, the dispatch
table, indirect calls) then goes through the wrapper, which costs one check
until a plugin hooks the function and then calls the runtime's
recomp_foundry_hook_call (port patch 0002).

Run it after the port generates its code (Recompile.ps1 / Build-From-Iso.ps1)
and before building. It is idempotent; --remove restores the generated code.
"""
import re
from pathlib import Path

HOOK_FILE = "foundry_hooks.c"
DEF = re.compile(r"^void sub_([0-9A-F]{8})(_body)?\(void\)$", re.M)


def _definitions(gen_dir):
    """{address: (file, renamed)} for every generated function definition."""
    out = {}
    for f in sorted(Path(gen_dir).glob("*.c")):
        if f.name == HOOK_FILE:
            continue
        text = f.read_text(encoding="latin-1")
        for m in DEF.finditer(text):
            out[int(m.group(1), 16)] = (f, bool(m.group(2)))
    return out


def _rename(path, renames):
    """renames: {address: to_body (True) or back (False)}"""
    text = path.read_text(encoding="latin-1")

    def sub(m):
        a = int(m.group(1), 16)
        if a not in renames:
            return m.group(0)
        return f"void sub_{m.group(1)}{'_body' if renames[a] else ''}(void)"

    path.write_text(DEF.sub(sub, text), encoding="latin-1", newline="")


def wrapper_source(addresses):
    lines = [
        "/* Generated by Mercenaries Foundry (python -m mercfoundry port-hooks). Do not edit.",
        " * Wrappers that let plugins hook these game functions; see the port patch",
        " * \"Plugin function hooks\" (recomp_foundry_hook_call in recomp_manual.c). */",
        "#include <stdint.h>",
        "typedef void (*foundry_func_t)(void);",
        "extern volatile uint8_t g_foundry_hook_on[];",
        "void recomp_foundry_hook_call(unsigned index, uint32_t address, foundry_func_t body);",
        "",
        "static const uint32_t foundry_addresses[] = {",
    ]
    for i in range(0, len(addresses), 6):
        lines.append("    " + ", ".join(f"0x{a:08X}u" for a in addresses[i:i + 6]) + ",")
    lines += ["};", "",
              "const uint32_t *foundry_hook_table(unsigned *count)",
              "{",
              f"    *count = {len(addresses)}u;",
              "    return foundry_addresses;",
              "}", ""]
    for i, a in enumerate(addresses):
        n = f"sub_{a:08X}"
        lines.append(f"void {n}_body(void);")
        lines.append(f"void {n}(void) {{ if (!g_foundry_hook_on[{i}]) {{ {n}_body(); return; }} "
                     f"recomp_foundry_hook_call({i}u, 0x{a:08X}u, {n}_body); }}")
    return "\n".join(lines) + "\n"


def apply(gen_dir, addresses, remove=False):
    """Make exactly `addresses` hookable (or none with remove). Returns
    (hooked addresses, addresses with no generated definition)."""
    gen = Path(gen_dir)
    if not (gen / "recomp_dispatch.c").exists():
        raise FileNotFoundError(f"{gen} doesn't look like the port's recomp/gen folder")
    defs = _definitions(gen)
    wanted = set() if remove else set(addresses)
    missing = sorted(a for a in wanted if a not in defs)
    per_file = {}
    for a, (f, renamed) in defs.items():
        want = a in wanted
        if want != renamed:
            per_file.setdefault(f, {})[a] = want
    for f, renames in per_file.items():
        _rename(f, renames)
    hooked = sorted(a for a in wanted if a in defs)
    target = gen / HOOK_FILE
    if hooked:
        target.write_text(wrapper_source(hooked), encoding="utf-8", newline="\n")
    elif target.exists():
        target.unlink()
    return hooked, missing


def map_addresses(doc):
    """Every named function in the function map."""
    return sorted(int(e["address"], 16) for e in doc["functions"] if e.get("names"))
